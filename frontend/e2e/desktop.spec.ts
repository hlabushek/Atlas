import {test,expect} from '@playwright/test';
import {openPanel} from './navigation';
test('owner registers, grants, queues and cancels an offline device',async({page})=>{
 test.setTimeout(60000);
 test.skip(!process.env.ATLAS_E2E_PASSWORD,'Set ATLAS_E2E_PASSWORD');
 await page.goto('/');
 await page.getByLabel('Пароль владельца').fill(process.env.ATLAS_E2E_PASSWORD!);
 await page.getByRole('button',{name:'Войти в Atlas'}).click();
 await openPanel(page,'Устройства');
 const name='E2E устройство '+Date.now();
 await page.getByLabel('Имя устройства').fill(name);
 await page.getByLabel('Отпечаток сертификата устройства').fill(String(Date.now()).padStart(64,'a'));
 await page.getByRole('button',{name:'Зарегистрировать устройство'}).click();
 const card=page.locator('article.device').filter({hasText:name});
 await expect(card).toContainText('ОТКЛЮЧЁН');
 await card.getByLabel('Разрешить устройство').check();
 await card.getByLabel('Разрешённые каталоги').fill('docs');
 await card.getByLabel('Чтение текста',{exact:true}).check();
 await card.getByRole('button',{name:'Сохранить доступ'}).click();
 await expect(card).toContainText('РАЗРЕШЁН');
 const id=await card.getAttribute('data-device-id');
 const originalTool=(await (await page.request.get('/api/tools')).json()).find((x:any)=>x.name==='desktop.read');
 await openPanel(page,'Инструменты');
 const tool=page.locator('.content article').filter({hasText:'desktop.read'});
 const allow=tool.getByRole('button',{name:'Снять запрет'});
 await expect(tool).toBeVisible();
 if(await allow.count())await allow.click();
 await expect(tool).toContainText('ДОСТУПЕН');
 await openPanel(page,'Устройства');
 await page.getByLabel('Устройство для действия').selectOption(id!);
 await page.getByLabel('Относительный путь').fill('e2e.txt');
 const queued=page.waitForResponse(r=>r.url().endsWith('/api/tasks')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Создать запрос устройства'}).click();
 const task=await (await queued).json();
 await expect.poll(async()=> (await (await page.request.get('/api/tasks/'+task.id)).json()).status,{timeout:20000}).toBe('WAITING_APPROVAL');
 await page.getByRole('button',{name:'Подтверждения',exact:true}).click();
 const approval=page.locator('.content article').filter({hasText:id!});
 await approval.getByRole('button',{name:'Разрешить действие'}).click();
 await expect.poll(async()=> (await (await page.request.get('/api/tasks/'+task.id)).json()).status,{timeout:20000}).toBe('WAITING_DEVICE');
 await openPanel(page,'Устройства');
 await card.getByRole('button',{name:'Журнал команд'}).click();
 await expect(card).toContainText('PENDING');
 await page.getByRole('button',{name:'Активность',exact:true}).click();
 const taskCard=page.locator('article.task').filter({hasText:task.id.slice(0,8)});
 await taskCard.getByRole('button',{name:'Отменить',exact:true}).click();
 await expect(taskCard).toContainText('CANCELLED');
 await openPanel(page,'Устройства');
 await card.getByRole('button',{name:'Журнал команд'}).click();
 await expect(card).toContainText('CANCELLED');
 const revoke=page.waitForResponse(r=>r.url().endsWith('/api/devices/'+id)&&r.request().method()==='PUT');
 await card.getByRole('button',{name:'Отозвать доступ'}).click();
 const revoked=await revoke;
 expect(revoked.status(),await revoked.text()).toBe(200);
 await expect(card).toContainText('ОТКЛЮЧЁН');
 await page.request.put('/api/tools/desktop.read/permission',{headers:{'X-Atlas-Client':'web'},data:{allowed:!originalTool.blocked}});
});
